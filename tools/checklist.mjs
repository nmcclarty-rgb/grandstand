/**
 * Generate the fact-checking checklist for the question bank.
 *
 *   node tools/checklist.mjs            # writes verification/
 *   node tools/checklist.mjs --summary  # just print the state of play
 *
 * The bank is written from memory and has never been checked against a source.
 * That is the largest open risk in the project, and the only way it gets
 * closed is by somebody sitting down with a reference work and working
 * through it — so this turns "verify 205 facts" into a tick-box job that can
 * be handed to anyone, done in chunks, and resumed.
 *
 * Output is ordered by risk, because the list will not be finished in one
 * sitting and the top of it should be the part that matters:
 *
 *   high  a figure that can still change, or one already marked approximate
 *   med   a closed record held by a retired player — stable, but unchecked
 *   low   definitional (scoring values, team sizes) or a well-known date
 *
 * Sign-off goes in src/data/verified.json, keyed by question id. Ids are
 * derived from question content, so correcting a number automatically drops
 * it back onto the list rather than leaving a stale tick against it.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { QUESTIONS, SPORTS } from '../src/data/questions.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'verification');

const verified = JSON.parse(readFileSync(join(ROOT, 'src/data/verified.json'), 'utf8'));
const isDone = (id) => Object.prototype.hasOwnProperty.call(verified, id) && id !== '_README';

const RISK_ORDER = { high: 0, med: 1, low: 2 };
const RISK_LABEL = {
  high: 'HIGH — can still change, or already flagged approximate',
  med: 'MEDIUM — a closed record, but never checked',
  low: 'LOW — definitional or a well-known date',
};

const outstanding = QUESTIONS.filter((q) => !isDone(q.id));
const done = QUESTIONS.length - outstanding.length;

// ── summary, always printed ───────────────────────────────────────────────
const byRisk = {};
for (const q of QUESTIONS) {
  byRisk[q.risk] = byRisk[q.risk] || { total: 0, done: 0 };
  byRisk[q.risk].total++;
  if (isDone(q.id)) byRisk[q.risk].done++;
}

console.log(`\nQUESTION BANK VERIFICATION`);
console.log(`  ${done} of ${QUESTIONS.length} checked (${Math.round((done / QUESTIONS.length) * 100)}%)\n`);
for (const risk of ['high', 'med', 'low']) {
  const r = byRisk[risk];
  if (!r) continue;
  const bar = '█'.repeat(Math.round((r.done / r.total) * 24)).padEnd(24, '·');
  console.log(`  ${risk.padEnd(5)} ${bar} ${String(r.done).padStart(3)}/${r.total}`);
}

if (process.argv.includes('--summary')) {
  console.log('');
  process.exit(0);
}

// ── markdown checklist ────────────────────────────────────────────────────
const esc = (s) => String(s).replace(/\|/g, '\\|');
let md = `# Question bank — verification checklist

${done} of ${QUESTIONS.length} checked. Generated by \`node tools/checklist.mjs\`; do not edit by hand.

**How to use this.** Work top down — the list is ordered by how likely a figure
is to be wrong or to have drifted. For each entry, check the numbers against
the suggested source, then record it in \`src/data/verified.json\`:

\`\`\`json
"<id>": { "by": "your initials", "on": "YYYY-MM-DD", "source": "where you checked" }
\`\`\`

Found a wrong number? Fix it in \`src/data/questions.js\` and leave it off the
verified list — ids are derived from content, so a correction automatically
drops the question back onto this checklist.

Two rules the bank is built on, worth keeping as you go:
prefer **retired players and closed records** over active ones, and never allow
**two options to share the top or bottom value** (\`validate.mjs\` fails on it).

`;

let csv = 'id,risk,sport,unit,prompt,option_1,value_1,option_2,value_2,option_3,value_3,source_hint\n';

for (const risk of ['high', 'med', 'low']) {
  const group = outstanding.filter((q) => q.risk === risk)
    .sort((a, b) => a.sport.localeCompare(b.sport));
  if (!group.length) continue;

  md += `\n## ${RISK_LABEL[risk]}\n\n${group.length} outstanding.\n`;
  let sport = null;
  for (const q of group) {
    if (q.sport !== sport) {
      sport = q.sport;
      md += `\n### ${SPORTS[sport] ? SPORTS[sport].name : sport}\n\n`;
      md += `*Suggested source: ${q.src}*\n\n`;
    }
    md += `- [ ] \`${q.id}\` — **${esc(q.most)}** *(${esc(q.unit)})*\n`;
    for (const o of q.options) md += `    - ${esc(o.label)} — **${o.value}**\n`;
    if (q.note) md += `    - <sub>note shown to the player: ${esc(q.note)}</sub>\n`;

    const cells = [q.id, q.risk, q.sport, q.unit, q.most];
    for (const o of q.options) cells.push(o.label, o.value);
    cells.push(q.src);
    csv += cells.map((c) => `"${String(c).replace(/"/g, '""')}"`).join(',') + '\n';
  }
}

if (!outstanding.length) md += '\nNothing outstanding. Every question has been checked.\n';

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, 'checklist.md'), md);
writeFileSync(join(OUT, 'checklist.csv'), csv);

console.log(`\n  wrote verification/checklist.md  (${outstanding.length} outstanding)`);
console.log(`  wrote verification/checklist.csv (same, for a spreadsheet)\n`);
