/**
 * Bundle GRANDSTAND into one self-contained .html file.
 *
 *   node tools/bundle.mjs [outfile]      (default: dist/grandstand.html)
 *
 * Why this exists: the game is authored as plain ES modules across a dozen
 * files, which is lovely to work on and awkward to host. A single file opens
 * from a phone, a USB stick, an email attachment or any static host, with no
 * server, no MIME-type configuration and no module resolution to go wrong.
 *
 * It is a tiny CommonJS-style bundler rather than a real one on purpose: no
 * build toolchain, no node_modules, nothing to keep up to date. It only
 * understands the handful of import/export forms this codebase actually uses,
 * and it THROWS on anything else rather than quietly emitting broken output —
 * a bundler that silently drops an export is far worse than one that refuses.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const SRC = join(ROOT, 'src');
const ENTRY = join(SRC, 'main.js');
// Output goes to docs/index.html because GitHub Pages' "deploy from a branch"
// mode serves only the repository root or /docs. The root is already taken by
// the development shell (which loads src/ as live modules), so /docs it is —
// one settings click, no CI, nothing to keep up to date.
const OUT = process.argv[2] ? resolve(process.argv[2]) : join(ROOT, 'docs', 'index.html');

const key = (abs) => relative(SRC, abs).split('\\').join('/');

// ── the only import/export shapes we accept ───────────────────────────────
const IMPORT_RE = /^import\s*\{([\s\S]*?)\}\s*from\s*['"]([^'"]+)['"];?\s*$/;
const EXPORT_DECL_RE = /^export\s+(const|let|var|function|class|async function)\s+([A-Za-z_$][\w$]*)/;
const EXPORT_LIST_RE = /^export\s*\{([^}]*)\}\s*;?\s*$/;

function parseModule(abs) {
  const text = readFileSync(abs, 'utf8');
  const lines = text.split('\n');
  const out = [];
  const exported = new Set();
  const deps = [];

  for (let i = 0; i < lines.length; i++) {
    let line = lines[i];

    // An import may span several lines; glue them up to the closing quote.
    if (/^import\s/.test(line)) {
      let stmt = line;
      while (!/from\s*['"][^'"]+['"]\s*;?\s*$/.test(stmt) && i + 1 < lines.length) {
        stmt += '\n' + lines[++i];
      }
      const m = stmt.replace(/\n/g, ' ').match(IMPORT_RE);
      if (!m) throw new Error(`${key(abs)}: unsupported import form:\n  ${stmt.trim()}`);
      const spec = m[2];
      if (!spec.startsWith('.')) throw new Error(`${key(abs)}: bare import "${spec}" — nothing external is allowed`);
      const target = resolve(dirname(abs), spec);
      deps.push(target);
      const names = m[1].split(',').map((s) => s.trim()).filter(Boolean)
        .map((s) => {
          const as = s.split(/\s+as\s+/);
          return as.length === 2 ? `${as[0].trim()}: ${as[1].trim()}` : s;
        });
      out.push(`const { ${names.join(', ')} } = __req(${JSON.stringify(key(target))});`);
      continue;
    }

    if (/^export\s+default\b/.test(line)) throw new Error(`${key(abs)}: export default is not supported`);

    const listed = line.match(EXPORT_LIST_RE);
    if (listed) {
      for (const n of listed[1].split(',').map((s) => s.trim()).filter(Boolean)) {
        if (/\s+as\s+/.test(n)) throw new Error(`${key(abs)}: renamed export "${n}" is not supported`);
        exported.add(n);
      }
      out.push('');            // the names are already in scope
      continue;
    }

    const decl = line.match(EXPORT_DECL_RE);
    if (decl) {
      exported.add(decl[2]);
      out.push(line.replace(/^export\s+/, ''));
      continue;
    }

    if (/^export\b/.test(line)) throw new Error(`${key(abs)}: unrecognised export:\n  ${line.trim()}`);
    out.push(line);
  }

  return { key: key(abs), body: out.join('\n'), exported: [...exported], deps };
}

// ── walk the graph from the entry point ───────────────────────────────────
const modules = new Map();
(function collect(abs) {
  const k = key(abs);
  if (modules.has(k)) return;
  const mod = parseModule(abs);
  modules.set(k, mod);
  for (const d of mod.deps) collect(d);
})(ENTRY);

const pieces = [...modules.values()].map((m) => `
// ─── ${m.key} ${'─'.repeat(Math.max(0, 60 - m.key.length))}
__def(${JSON.stringify(m.key)}, function (__exports, __req) {
${m.body}
Object.assign(__exports, { ${m.exported.join(', ')} });
});`).join('\n');

const runtime = `(function () {
'use strict';
// Minimal module registry, generated by tools/bundle.mjs. Do not edit by hand —
// edit src/ and re-run the bundler.
var __mods = {}, __cache = {};
function __def(name, fn) { __mods[name] = fn; }
function __req(name) {
  if (__cache[name]) return __cache[name];
  if (!__mods[name]) throw new Error('missing module: ' + name);
  var ex = (__cache[name] = {});
  __mods[name](ex, __req);
  return ex;
}
${pieces}
__req(${JSON.stringify(key(ENTRY))});
})();`;

// ── stitch it into the page ───────────────────────────────────────────────
let html = readFileSync(join(ROOT, 'index.html'), 'utf8');
const TAG = '<script type="module" src="./src/main.js"></script>';
if (!html.includes(TAG)) throw new Error('index.html no longer contains the expected entry script tag');
html = html.replace(TAG, `<script>\n${runtime}\n</script>`);
html = html.replace('<title>Grandstand</title>',
  '<title>Grandstand</title>\n<!-- Generated by tools/bundle.mjs. Do not edit: change src/ and rebuild. -->');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, html);

const kb = (Buffer.byteLength(html) / 1024).toFixed(0);
console.log(`bundled ${modules.size} modules -> ${relative(process.cwd(), OUT)} (${kb} KB)`);
for (const m of modules.values()) console.log(`  ${m.key.padEnd(24)} ${m.exported.length} exports`);
