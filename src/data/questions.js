/**
 * GRANDSTAND — question bank.
 *
 * Every question is a comparison between three real people/teams where the
 * answer is a WHOLE NUMBER. That number is the damage you deal.
 *
 * Each entry does double duty:
 *   `most`  is asked on your STRIKE turn  (pick the biggest number = biggest hit)
 *   `least` is asked on your BLOCK turn   (pick the smallest number = best block)
 *
 * Design rule: prefer RETIRED players and CLOSED records. A bank full of active
 * players rots. See README "Keeping the bank honest".
 */

/**
 * The BLOCK prompt is derived from the STRIKE prompt rather than written
 * twice. Hand-writing both is how you end up shipping "Who won FEWER?" with
 * no noun in it — the block prompt has to stand alone, because the player
 * never sees the strike wording next to it.
 */
const FLIP = [
  [/\bMOST recently\b/g, 'EARLIEST'],
  [/\bMOST recent\b/g, 'EARLIEST'],
  [/\bMOST\b/g, 'FEWEST'],
  [/\bMORE\b/g, 'FEWER'],
  [/\bBIGGEST\b/g, 'SMALLEST'],
  [/\bHIGHEST\b/g, 'LOWEST'],
  [/\bOLDEST\b/g, 'YOUNGEST'],
  [/\bLONGEST\b/g, 'SHORTEST'],
  [/\bFURTHEST\b/g, 'SHORTEST'],
  [/\bDEEPEST\b/g, 'SHALLOWEST'],
];

function flip(prompt) {
  let out = prompt;
  for (const [re, word] of FLIP) {
    if (re.test(out)) { out = out.replace(re, word); break; }
  }
  return out;
}

